// Шаг 1: Правило 1 и 2 — Единственная входная ссылка
fn first_word(s: &str) -> &str {
    // Нам не нужно писать <'a>(s: &'a str) -> &'a str!
    // Компилятор сам сопоставит s и время жизни 'a (Правило 1)
    // и этот же lifetime 'a отдает возвращаемому строковому срезу (Правило 2).
    s.split_whitespace().next().unwrap_or("")
}

fn main() {
    let greeting = String::from("Rust 2026: Concurrency");
    let word = first_word(&greeting);
    
    println!("Первое слово в строке: {word}");
}

// ! **1. Правила 1 и 2: Единственная входная ссылка**
// ! - Правило 1: Каждой входной ссылке компилятор автоматически выделяет свой lifetime параметр.
// ! - Правило 2: Если входная ссылка ровно одна, её время жизни автоматически передаётся всем выходным ссылкам.
// ! - Код выглядит лаконично и читаемо — без лишних аннотаций `'a`.

// ---

// Шаг 2: Правило 3 — Методы структуры с &self

// Rust требует явно объявить <'a> у самой структуры, чтобы компилятор знал:
// экземпляр LogEntry не должен прожить дольше текста, на который он ссылается.
struct LogEntry<'a> {
    message: &'a str,
}

impl<'a> LogEntry<'a> {
    // А вот в сигнатуре функции добавлять 'a уже не нужно
    // Хотя у метода два ссылочных аргумета (&self и _fallback: &str),
    // компилятор по Правилу 3 автоматически связывает выходной срез с &self.
    // rustc рассматривает сигнатуру функции как: fn extract_tag<'b>(&'b self, _fallback: &str) -> &'b str
    fn extract_tag(&self, _fallback: &str) -> &str {
        if self.message.starts_with('[') {
            if let Some(end) = self.message.find(']') {
                return &self.message[1..end];
            }
        }
        "GENERAL"
    }
}

fn main() {
    let entry = LogEntry {
        message: "[AUTH] Пользователь успешно вошёл в систему",
    };
    let default_tag = "DEFAULT";
    
    let tag = entry.extract_tag(default_tag);
    println!("Тег записи лога: {tag}");
}

// ! **2. Правило 3: Методы с &self или &mut self**
// ! - Ещё раз, откуда взялся `'a` у структуры? Поле `message` хранит ссылку `&'a str`, поэтому структуре нужна аннотация (подробнее в разделе 2).
// ! - Но в самом методе `extract_tag` аннотации не нужны: Правило 3 автоматически связывает выходную ссылку с `&self`.
// ! - Компилятор не путается между `&self` и `_fallback`: приоритет возврата всегда отдаётся времени жизни экземпляра структуры.

// ---

// Шаг 3: Когда автоматика не выручает — Неоднозначность
fn choose_longest<'a>(first: &'a str, second: &'a str) -> &'a str {
    // Входных ссылок две, а возвращается одна. Компилятор не знает,
    // какая ветка сработает в рантайме, поэтому требует явно связать их через <'a>.
    if first.len() > second.len() {
        first
    } else {
        second
    }
}

fn main() {
    let word1 = "Ferris";
    let word2 = "Rustacean";

    let winner = choose_longest(word1, word2);
    println!("Более длинное слово: {winner}");
}

