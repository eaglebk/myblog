// Шаг 1: Ссылка &'static str vs Ограничение типа T: 'static
fn print_static(msg: &'static str) {
    println!("Строковый литерал вшит в секцию данных бинарника: {msg}");
}

fn spawn_worker<T: 'static>(val: T) {
    // T: 'static означает: тип T либо владеет данными без ссылок (String, Vec, u32),
    // либо содержит только 'static ссылки.
    println!("Значение изолировано и может жить сколь угодно долго.");
}

fn main() {
    print_static("Привет, бинарник!");
    
    let owned_string = String::from("Динамически созданный владеющий String");
    spawn_worker(owned_string);
}

// ! **1. Статическая память 'static**
// ! - `&'static str` указывает на данные, вшитые в бинарник и существующие всё время работы программы.
// ! - Ограничение `T: 'static` НЕ означает, что переменная живет вечно: оно лишь запрещает короткоживущие ссылки внутри `T`.

