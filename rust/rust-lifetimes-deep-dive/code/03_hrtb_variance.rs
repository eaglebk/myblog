// Шаг 3: Вариантность (Variance) — Ковариантность и Инвариантность
fn inspect_slice<'a>(slice: &'a str) {
    println!("Осмотр среза: {slice}");
}

fn main() {
    // 1. Ковариантность (&'a T):
    // Ссылку с большим временем жизни ('static) можно передать туда, где ждут меньшее ('a)
    let static_literal: &'static str = "Вечные данные";
    inspect_slice(static_literal);

    // 2. Инвариантность (&'a mut T):
    // Для мутабельных ссылок подмена времен жизни строго запрещена!
    let mut data: &'static str = "Исходный текст";
    {
        let short_lived = String::from("Короткая строка");
        // Если бы Rust разрешил присвоить &mut data ссылку на short_lived,
        // после уничтожения short_lived переменная data ссылалась бы на мусор!
        let _ref_mut: &mut &'static str = &mut data;
    }
    println!("Инвариантность защищает мутабельные ссылки от подмены: {data}");
}

// ! **3. Вариантность (Variance)**
// ! - Ковариантность (`&'a T`): Rust безопасно сужает более долгоживущую ссылку (например `'static`) до локального `'a`.
// ! - Инвариантность (`&'a mut T`): Для изменяемых ссылок подмена времён жизни запрещена, чтобы избежать записи мусора.
