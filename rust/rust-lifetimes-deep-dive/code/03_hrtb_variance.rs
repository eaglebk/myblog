// Шаг 2: Времена жизни "на лету" (High-Rank Trait Bounds — for<'a>)

// 💡 Кто выбирает время жизни ссылки?
// Если бы мы написали 'a снаружи: fn process<'a, F>(f: F) where F: Fn(&'a str),
// то вызывающий код должен был бы предоставить ссылку заранее. Мы не смогли бы передать локальные данные!
// С синтаксисом for<'a> замыкание обещает принять ссылку ЛЮБОГО времени жизни в момент вызова.
fn process_incoming_event<F>(f: F)
where
    F: for<'a> Fn(&'a str) -> String,
{
    // Данные рождаются прямо внутри функции (например, прочитали пакет из сокета):
    let local_payload = String::from("EVENT_ID_42: telemetry data");
    
    // Передаем ссылку на локальную переменную в замыкание:
    let summary = f(&local_payload);
    println!("Результат обработки: {summary}");
}

fn main() {
    // Передаем замыкание, готовое работать с любым временным срезом:
    process_incoming_event(|raw_data| {
        format!("Обработано {} символов", raw_data.len())
    });
}

// ! **2. Времена жизни на лету (for<'a>)**
// ! - Кто решает, сколько живёт ссылка: если 'a снаружи, время жизни фиксирует вызывающий код до вызова.
// ! - Синтаксис `for<'a>` переносит решение внутрь: замыкание готово принять ссылку даже на временную переменную из сокета.
// ! - Это основа работы коллбэков в асинхронных фреймворках (Tokio, Actix, Axum).

